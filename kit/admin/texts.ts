export type KitTextKey = keyof (typeof TEXTS)["en"]

/** `k("todo")`, `k("pcs", { count: 3 })`: the shared cards' texts in the admin's language. */
export function useKitText() {
  const { i18n } = useTranslation()
  const dict = (i18n.language ?? "").toLowerCase().startsWith("pl") ? TEXTS.pl : TEXTS.en
  return (key: KitTextKey, params: Record<string, string | number> = {}) =>
    dict[key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(params[name] ?? ""))
}
